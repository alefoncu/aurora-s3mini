"""Generates res/values-night/colors.xml for the stock-app overlays by classifying each plain colour of the app.
Usage: gen_night.py <app> <dump-file> [--print]
Day values are untouched; night swaps light surfaces / dark text for the night palette (design/tokens.md)."""
import re, sys, os
BG, SURFACE, LINE = 'FF14123A', 'FF1E1B4B', 'FF2E2B66'
TEXT, TEXT2, DIS = 'FFF2F1FF', 'FFA3A1C8', '66F2F1FF'
MAT = {  # AppCompat/Material copies that many apps carry
 'foreground_material_light': TEXT, 'background_material_light': BG, 'background_floating_material_light': SURFACE,
 'primary_material_light': SURFACE, 'primary_dark_material_light': BG, 'button_material_light': 'FF3A3779',
 'primary_text_default_material_light': TEXT, 'secondary_text_default_material_light': TEXT2,
 'primary_text_disabled_material_light': DIS, 'secondary_text_disabled_material_light': '4DF2F1FF',
 'bright_foreground_material_light': TEXT, 'bright_foreground_disabled_material_light': DIS,
 'bright_foreground_inverse_material_light': BG, 'dim_foreground_material_light': TEXT2,
 'dim_foreground_disabled_material_light': '66A3A1C8', 'highlighted_text_material_light': '664F82FF',
 'switch_thumb_normal_material_light': 'FFDAD8F5', 'switch_thumb_disabled_material_light': 'FF6A678F',
}
SKIP = re.compile(r'^(abc_|notification_|design_|cardview_|material_)|dim_color|photo_|camera_|font_color|tile|status_bar_black|download_failed_timestamp|permission_text')
def parse(dump):
    lines = open(dump).read().split('\n'); out = {}
    for i, l in enumerate(lines):
        m = re.match(r'\s+resource 0x\w+ color/(\w+)', l)
        if m:
            v = re.match(r'\s+\(\) #([0-9a-fA-F]{6,8})$', lines[i + 1])
            if v: out[m.group(1)] = v.group(1).lower()
    return out
def argb(h):
    h = h.lower()
    if len(h) == 6: h = 'ff' + h
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), int(h[6:8], 16)
def classify(name, h):
    n = name.lower(); a, r, g, b = argb(h); lum = .299 * r + .587 * g + .114 * b
    if name in MAT: return MAT[name]
    if SKIP.match(name): return None
    if re.search(r'(^|_)(action|actionbar|toolbar|tab|status|statusbar|bar)(_|$)', n) and a == 255: return None
    chroma = max(r, g, b) - min(r, g, b)
    if chroma > 30: return None
    if a == 255 and lum >= 200:
        if re.search(r'divider|separator|line', n): return LINE
        if re.search(r'text|icon|tint|ripple|shadow|foreground|button|accent|selected|highlight', n): return None
        return SURFACE if lum >= 250 else BG
    if r == g == b == 0 and a < 255:
        if a >= 0xb0: return TEXT
        if a >= 0x6a: return TEXT2
        if re.search(r'divider|separator|line', n): return LINE
        return None
    if a == 255 and lum <= 120 and re.search(r'text', n): return TEXT if lum <= 70 else TEXT2
    if a == 255 and 120 < lum < 160 and re.search(r'text|hint|secondary|subhead', n): return TEXT2
    return None
if __name__ == '__main__':
    app, dump = sys.argv[1], sys.argv[2]
    cols = parse(dump); res = {}
    for k, v in cols.items():
        c = classify(k, v)
        if c: res[k] = c
    d = os.path.expanduser(f'~/ios-reskin/work/{app}/res/values-night'); os.makedirs(d, exist_ok=True)
    body = ''.join(f'    <color name="{k}">#{v}</color>\n' for k, v in sorted(res.items()))
    open(f'{d}/colors_auto.xml', 'w').write('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/gen_night.py -->\n<resources>\n' + body + '</resources>\n')
    print(app, len(res), 'night colours')
    if '--print' in sys.argv:
        for k, v in sorted(res.items()): print(f'  {k}: #{cols[k]} -> #{v}')
